// Package pixelart draws Tiny-FTPd's icons from ASCII pixel grids, one
// character per pixel, so the art lives in the code and needs no image files.
package pixelart

import (
	"bytes"
	"image"
	"image/color"
	"image/png"
	"strings"
)

// palette maps grid characters to colours, in palette index order. '.' is
// transparent.
var palette = []struct {
	char   byte
	colour color.RGBA
}{
	{'.', color.RGBA{}},
	{'K', color.RGBA{0, 0, 0, 255}},
	{'D', color.RGBA{192, 128, 0, 255}},   // folder shade
	{'Y', color.RGBA{255, 200, 40, 255}},  // folder
	{'L', color.RGBA{255, 240, 150, 255}}, // folder highlight
	{'g', color.RGBA{0, 128, 0, 255}},
	{'G', color.RGBA{60, 220, 60, 255}},
	{'b', color.RGBA{0, 0, 160, 255}},
	{'B', color.RGBA{64, 96, 255, 255}},
	{'W', color.RGBA{255, 255, 255, 255}},
	{'S', color.RGBA{192, 192, 192, 255}}, // silver
	{'M', color.RGBA{128, 128, 128, 255}}, // grey
	{'N', color.RGBA{0, 0, 128, 255}},     // navy
	{'A', color.RGBA{150, 200, 255, 255}}, // sky
	{'R', color.RGBA{204, 0, 0, 255}},     // red
	{'r', color.RGBA{255, 140, 170, 255}}, // eraser pink
}

// Parse turns a pixel grid into a paletted image. It panics on a malformed
// grid, since grids are constants.
func Parse(grid string) *image.Paletted {
	rows := strings.Fields(grid)
	pal := make(color.Palette, len(palette))
	index := map[byte]uint8{}
	for i, p := range palette {
		pal[i] = p.colour
		index[p.char] = uint8(i)
	}
	img := image.NewPaletted(image.Rect(0, 0, len(rows[0]), len(rows)), pal)
	for y, row := range rows {
		if len(row) != len(rows[0]) {
			panic("pixelart: ragged grid")
		}
		for x := range len(row) {
			i, ok := index[row[x]]
			if !ok {
				panic("pixelart: unknown colour " + string(row[x]))
			}
			img.SetColorIndex(x, y, i)
		}
	}
	return img
}

// Scale enlarges src n times with nearest-neighbour sampling, keeping the
// pixels crisp.
func Scale(src *image.Paletted, n int) *image.Paletted {
	b := src.Bounds()
	dst := image.NewPaletted(image.Rect(0, 0, b.Dx()*n, b.Dy()*n), src.Palette)
	for y := range dst.Bounds().Dy() {
		for x := range dst.Bounds().Dx() {
			dst.SetColorIndex(x, y, src.ColorIndexAt(x/n, y/n))
		}
	}
	return dst
}

// PNG encodes img as a PNG.
func PNG(img image.Image) []byte {
	var b bytes.Buffer
	png.Encode(&b, img) // can't fail writing to a bytes.Buffer
	return b.Bytes()
}

